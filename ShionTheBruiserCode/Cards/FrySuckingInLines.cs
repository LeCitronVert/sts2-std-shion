/// <summary>
/// Gain Stars and deal damage equal to the enemy's Strength. Upgrade: costs 0.
/// </summary>
public class FrySuckingInLines() : FryTheCommanderCard(1,
    CardType.Attack, CardRarity.Uncommon,
    TargetType.AnyEnemy)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [
        new HasTargetVar(),
        new CalculationBaseVar(0),
        new CalculationExtraVar(1),
        new CalculatedVar("StarsAmount").WithMultiplier((_, target) => GetStrength(target)),
    ];

    private static int GetStrength(Creature? target) => Math.Max(0, target?.GetPowerAmount<StrengthPower>() ?? 0);

    protected override IEnumerable<IHoverTip> ExtraHoverTips => [HoverTipFactory.FromPower<StrengthPower>()];

    protected override async Task OnPlay(PlayerChoiceContext choiceContext, CardPlay play)
    {
        ArgumentNullException.ThrowIfNull(play.Target);
        var strength = GetStrength(play.Target);
        if (strength <= 0) return;

        await PlayerCmd.GainStars(strength, Owner);
        await DamageCmd.Attack(strength)
            .FromCard(this, play)
            .Targeting(play.Target)
            .WithHitFx("vfx/vfx_attack_slash")
            .Execute(choiceContext);
    }

    protected override void OnUpgrade()
    {
        EnergyCost.UpgradeBy(-1);
    }
}
