/// <summary>
/// Whenever you Retain a card, gain 1 (2) Vigor.
/// </summary>
public class FryMeditationPowerup() : FryTheCommanderCard(1, //todo : choose cost
    CardType.Power, CardRarity.Uncommon,
    TargetType.Self)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [new PowerVar<MeditationPowerup>(1M)];

    protected override IEnumerable<IHoverTip> ExtraHoverTips => [HoverTipFactory.FromPower<VigorPower>()];

    protected override async Task OnPlay(PlayerChoiceContext choiceContext, CardPlay play)
    {
        await PowerCmd.Apply<MeditationPowerup>(choiceContext, Owner.Creature, DynamicVars["MeditationPowerup"].BaseValue, Owner.Creature, this);
    }

    protected override void OnUpgrade()
    {
        DynamicVars["MeditationPowerup"].UpgradeValueBy(1M);
    }
}
