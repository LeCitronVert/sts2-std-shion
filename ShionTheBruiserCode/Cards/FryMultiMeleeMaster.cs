/// <summary>
/// Deal 8 (10) damage. Gain 1 energy per Attack in your Hand.
/// </summary>
public class FryMultiMeleeMaster() : FryTheCommanderCard(2,
    CardType.Attack, CardRarity.Uncommon,
    TargetType.AnyEnemy)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [
        new DamageVar(8M, ValueProp.Move),
        new CalculationBaseVar(0),
        new CalculationExtraVar(1),
        new CalculatedVar("EnergyAmount").WithMultiplier((card, _) => CountAttacks(card)),
    ];

    private static int CountAttacks(CardModel card) =>
        card.CombatState is null ? 0 : PreviewHelper.OtherCardsInHand(card).Count(c => c.Type == CardType.Attack);

    protected override async Task OnPlay(PlayerChoiceContext choiceContext, CardPlay play)
    {
        ArgumentNullException.ThrowIfNull(play.Target);
        await DamageCmd.Attack(DynamicVars.Damage.BaseValue)
            .FromCard(this, play)
            .Targeting(play.Target)
            .WithHitFx("vfx/vfx_attack_slash")
            .Execute(choiceContext);

        var energy = PileType.Hand.GetPile(Owner).Cards.Count(c => c.Type == CardType.Attack);
        if (energy > 0) await PlayerCmd.GainEnergy(energy, Owner);
    }

    protected override void OnUpgrade()
    {
        DynamicVars.Damage.UpgradeValueBy(2M);
    }
}
