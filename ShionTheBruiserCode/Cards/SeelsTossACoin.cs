/// <summary>
/// Another player Gambles any number of cards in their Hand (they choose), and draws 1 card. (Retain.)
/// </summary>
public class SeelsTossACoin() : SeelsTheRecklessCard(0,
    CardType.Skill, CardRarity.Uncommon,
    TargetType.AnyAlly)
{
    protected override HashSet<CardTag> CanonicalTags => [SeelsCardTags.Gamble];

    public override CardMultiplayerConstraint MultiplayerConstraint => CardMultiplayerConstraint.MultiplayerOnly;

    protected override IEnumerable<DynamicVar> CanonicalVars => [new CardsVar(1)];

    protected override IEnumerable<IHoverTip> ExtraHoverTips => [
        HoverTipFactory.FromKeyword(SeelsCardKeywords.Gamble),
        HoverTipFactory.FromKeyword(SeelsCardKeywords.Erratic),
    ];

    protected override async Task OnPlay(PlayerChoiceContext choiceContext, CardPlay play)
    {
        ArgumentNullException.ThrowIfNull(play.Target?.Player);
        var player = play.Target.Player;
        await SeelsMechanicsHelper.GambleAnyNumber(choiceContext, player, this);
        await CardPileCmd.Draw(choiceContext, DynamicVars.Cards.BaseValue, player);
    }

    protected override void OnUpgrade()
    {
        AddKeyword(CardKeyword.Retain);
    }
}
