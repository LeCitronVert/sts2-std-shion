namespace ShionTheBruiser.ShionTheBruiserCode.Cards;

/// <summary>
/// Whenever an enemy breaks your Block, gain 1 (2) Strength.
/// </summary>
public class FryTodo4() : FryTheCommanderCard(2,
    CardType.Power, CardRarity.Rare,
    TargetType.Self)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [new PowerVar<FryTodo4Power>(1M)];

    protected override IEnumerable<IHoverTip> ExtraHoverTips => [HoverTipFactory.FromPower<StrengthPower>()];

    protected override async Task OnPlay(PlayerChoiceContext choiceContext, CardPlay play)
    {
        await PowerCmd.Apply<FryTodo4Power>(choiceContext, Owner.Creature, DynamicVars["FryTodo4Power"].BaseValue, Owner.Creature, this);
    }

    protected override void OnUpgrade()
    {
        DynamicVars["FryTodo4Power"].UpgradeValueBy(1M);
    }
}
